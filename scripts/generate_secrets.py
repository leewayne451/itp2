"""
Create / complete the git-ignored .env with strong random secrets.

    python scripts/generate_secrets.py

* Adds ONLY the keys that are missing — existing values (e.g. your SMTP settings)
  are never changed, so it is safe to run again at any time.
* Values come from Python's `secrets` module (CSPRNG). Nothing is printed.
* Standard library only, so it runs on Windows, macOS and Linux.

To ROTATE a secret, delete its line from .env and run this again, then
`docker compose up -d --force-recreate`. Note: a new POSTGRES_PASSWORD only takes
effect on a fresh database volume (`docker compose down -v`), a new MFA_ENC_KEY
makes existing TOTP enrolments unreadable (users must re-enrol), a new
AUDIT_HMAC_KEY makes earlier audit entries fail verification, and the Keycloak
secrets are read only when Keycloak first imports its realm (reset its volume).
"""
import base64
import os
import re
import secrets
import sys

ENV_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".env")


def _token():
    return secrets.token_urlsafe(48)          # 384 bits


def _fernet_key():
    return base64.urlsafe_b64encode(os.urandom(32)).decode()


SECRETS = [
    ("POSTGRES_PASSWORD", _token, "database owner password (schema/migrations at start-up)"),
    ("APP_DB_PASSWORD", _token, "restricted runtime database role (sj_app) used by every API request"),
    ("ANALYTICS_DB_PASSWORD", _token, "analytics container's read-mostly database role (sj_analytics, CHANGE 007)"),
    ("AUDIT_HMAC_KEY", _token, "seals the audit-trail hash chain (keep it; changing it breaks verification)"),
    ("MFA_ENC_KEY", _fernet_key, "legacy: decrypts pre-Keycloak TOTP secrets so they can be migrated"),
    ("CONSOLE_SECRET_KEY", _token, "signs the console's session cookie"),
    ("SERVICE1_SECRET_KEY", _token, "signs service1's session cookie"),
    ("SERVICE2_SECRET_KEY", _token, "signs service2's session cookie"),
    ("CONSOLE_CLIENT_SECRET", _token, "console -> backend client credential"),
    ("SERVICE1_CLIENT_SECRET", _token, "service1 -> backend client credential"),
    ("SERVICE2_CLIENT_SECRET", _token, "service2 -> backend client credential"),
    ("KEYCLOAK_DB_PASSWORD", _token, "Keycloak's own database"),
    ("KEYCLOAK_ADMIN_PASSWORD", _token, "Keycloak admin console, user 'kcadmin' (https://localhost:8443/admin)"),
    ("KEYCLOAK_BACKEND_CLIENT_SECRET", _token, "backend service account in Keycloak (user sync, events)"),
    ("OIDC_CONSOLE_SECRET", _token, "console's OpenID Connect client secret in Keycloak"),
    ("OIDC_SERVICE1_SECRET", _token, "service1's OpenID Connect client secret in Keycloak"),
    ("OIDC_SERVICE2_SECRET", _token, "service2's OpenID Connect client secret in Keycloak"),
]


def main():
    path = os.path.normpath(ENV_PATH)
    existing, newline = "", "\n"
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8", newline="") as f:
            existing = f.read()
        if "\r\n" in existing:
            newline = "\r\n"
    present = set(re.findall(r"^\s*([A-Z0-9_]+)\s*=\s*\S", existing, flags=re.M))

    missing = [(k, gen, why) for k, gen, why in SECRETS if k not in present]
    if not missing:
        print(f".env already has every secret ({len(SECRETS)}). Nothing changed.")
        return 0

    lines = ["", "# ---------------------------------------------------------------------------",
             "# Secrets generated by scripts/generate_secrets.py — keep this file private",
             "# (.env is git-ignored). Delete a line and re-run to rotate that secret.",
             "# ---------------------------------------------------------------------------"]
    for key, gen, why in missing:
        lines.append(f"# {why}")
        lines.append(f"{key}={gen()}")
    block = newline.join(lines) + newline
    if existing and not existing.endswith(("\n", "\r")):
        block = newline + block

    with open(path, "a", encoding="utf-8", newline="") as f:
        f.write(block)
    try:
        os.chmod(path, 0o600)                 # owner-only where the OS supports it
    except OSError:
        pass
    print(f"Added {len(missing)} secret(s) to {path}: {', '.join(k for k, _, _ in missing)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
